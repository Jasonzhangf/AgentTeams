#!/usr/bin/env node
/**
 * `agentteams join`: verify the relay is reachable, write or update the frozen
 * v4 agent config, and start the daemon detached.
 *
 * Ownership: config owns the file, credentials stay environment references, and
 * the CLI never invents an identity. An existing config with a different
 * identity is refused instead of rebuilt. When the start step fails the written
 * config is kept and the failure is reported; no second daemon is started.
 */
import { spawn } from 'node:child_process'
import { mkdirSync, readFileSync, renameSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { isIP } from 'node:net'
import { connect as tlsConnect } from 'node:tls'

const ENGINE_KINDS = new Set(['opencode', 'dsh'])

function fail(message) {
  process.stderr.write(`join: ${message}\n`)
  process.exitCode = 1
  throw new Error(message)
}

function take(argv, name, required = true) {
  const index = argv.indexOf(name)
  if (index < 0) {
    if (required) fail(`${name} is required`)
    return undefined
  }
  const value = argv[index + 1]
  if (value === undefined || value.startsWith('--')) fail(`${name} requires a value`)
  argv.splice(index, 2)
  return value
}

function parse(argv) {
  const remote = take(argv, '--remote')
  const endpoint = take(argv, '--endpoint')
  const serve = take(argv, '--serve')
  const name = take(argv, '--name', false)
  const configPath = resolve(take(argv, '--config', false) ?? 'agentteams.toml')
  const noStart = argv.includes('--no-start')
  // Verification is the default. A self-signed relay is trusted explicitly with
  // --ca; --insecure is the one bypass and it says so on stderr.
  const insecure = argv.includes('--insecure')
  const caPath = take(argv, '--ca', false)
  if (!/^wss:\/\/[^/\s]+$/u.test(remote)) fail('--remote must be a wss URL')
  const endpointMatch = /^([^:\s]+):(\d{1,5})$/u.exec(endpoint)
  if (!endpointMatch) fail('--endpoint must be ip:port')
  const port = Number(endpointMatch[2])
  if (port < 1 || port > 65_535) fail('--endpoint port is out of range')
  if (!ENGINE_KINDS.has(serve)) fail('--serve must be opencode or dsh')
  // Never invent an identity: two hosts on one address must not collide.
  if (name === undefined || name.length === 0) fail('--name is required')
  const agentId = name
  if (!/^[A-Za-z0-9][A-Za-z0-9._-]*$/u.test(agentId)) fail('--name must be a simple agent id')
  return {
    remote, endpoint: endpointMatch[0], ip: endpointMatch[1], port, serve, agentId, configPath, noStart, insecure,
    ...(caPath === undefined ? {} : { caPath: resolve(caPath) }),
  }
}

/**
 * A real TLS handshake against the relay; any admitted socket proves reachability.
 * The peer certificate is verified unless the caller asked for the explicit
 * bypass, so a hostname or trust mismatch fails here instead of at first use.
 */
function probe(remote, options, timeoutMs = 5_000) {
  const url = new URL(remote)
  const ca = options.caPath === undefined ? undefined : readFileSync(options.caPath)
  return new Promise((resolve) => {
    const socket = tlsConnect({
      host: url.hostname,
      port: Number(url.port || 443),
      // RFC 6066 forbids an IP literal as the SNI name; the certificate is then
      // matched against the IP subject alternative name.
      ...(isIP(url.hostname) === 0 ? { servername: url.hostname } : {}),
      ...(ca === undefined ? {} : { ca }),
      rejectUnauthorized: options.insecure !== true,
    })
    const done = (reachable, reason) => {
      socket.destroy()
      resolve({ reachable, ...(reason === undefined ? {} : { reason }) })
    }
    socket.setTimeout(timeoutMs, () => done(false, 'timeout'))
    socket.once('secureConnect', () => done(true))
    socket.once('error', (error) => done(false, error.message))
  })
}

function renderConfig(options) {
  return `# Generated by agentteams join. One file declares exactly one daemon.
# Credentials stay environment references; never write a secret here.
version = 4

[daemon]
kind = "agent"
id = "${options.agentId}"
hostId = "${options.agentId}-host"
accountId = "local"
scopeId = "local"
dataDirectory = "./state/${options.agentId}"

[engine]
kind = "${options.serve}"
workspace = "./workspace-${options.serve}"

[listen]
ip = "${options.ip}"
port = ${options.port}

[acp]
enabled = true
required = []
blacklist = []
clientCapabilities = []
callbackExecutor = "controller"

[relations]
allowed = ["peer"]

[discovery]
enabled = true
url = "${options.remote}"
credentialEnv = "AGENTTEAMS_RELAY_CREDENTIAL"
`
}

function readIdentity(configPath) {
  try {
    const text = readFileSync(configPath, 'utf8')
    const id = /^\s*id\s*=\s*"([^"]+)"/mu.exec(text)?.[1]
    return id === undefined ? null : { id }
  } catch (error) {
    if (error && error.code === 'ENOENT') return undefined
    throw error
  }
}

function writeAtomically(configPath, text) {
  mkdirSync(dirname(configPath), { recursive: true })
  const temporary = `${configPath}.${process.pid}.tmp`
  writeFileSync(temporary, text, { mode: 0o600 })
  renameSync(temporary, configPath)
}

function startDaemon(configPath) {
  const entry = resolve(dirname(new URL(import.meta.url).pathname), 'agentteams.mjs')
  const child = spawn(process.execPath, [entry, 'start', '--config', configPath], { detached: true, stdio: 'ignore' })
  child.unref()
  return child.pid
}

const options = parse(process.argv.slice(2))
const existing = readIdentity(options.configPath)
if (existing !== undefined && existing !== null && existing.id !== options.agentId) {
  fail(`${options.configPath} declares ${existing.id}, not ${options.agentId}; refusing to rebuild it`)
}
if (options.insecure) process.stderr.write('join: TLS verification bypassed (--insecure)\n')
const reachability = await probe(options.remote, options)
if (!reachability.reachable) {
  // The previous config stays untouched when the relay is unreachable.
  fail(`relay ${options.remote} is unreachable: ${reachability.reason ?? 'no reason'}`)
}
writeAtomically(options.configPath, renderConfig(options))
process.stdout.write(`join: wrote ${options.configPath} daemon=${options.agentId} relay=${options.remote} reachable=true\n`)
if (options.noStart) {
  process.stdout.write('join: start skipped (--no-start)\n')
} else {
  const pid = startDaemon(options.configPath)
  process.stdout.write(`join: started detached pid=${pid}\n`)
}
